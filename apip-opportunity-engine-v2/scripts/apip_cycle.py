"""APIP autonomous cycle v1: choose and record the next zero-cost experiment.

This is a local decision loop, not an AI model or an income guarantee. It uses
persistent JSONL events to avoid repeatedly selecting the same untested idea.
It never contacts anyone, spends money, or moves funds.
"""
from __future__ import annotations
import json
from datetime import datetime, timezone
from pathlib import Path
import sys
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from scripts.opportunity_engine import generate

EVENTS = ROOT / "data" / "experiment-events.jsonl"
NEXT = ROOT / "reports" / "apip-next-action.md"
STATE = ROOT / "reports" / "apip-cycle-state.json"

TERMINAL = {"TESTED_NO_DEMAND", "TESTED_DEMAND", "ABANDONED_WITH_REASON"}

def read_events():
    events=[]
    if EVENTS.exists():
        for line_no,line in enumerate(EVENTS.read_text(encoding="utf-8").splitlines(),1):
            if not line.strip(): continue
            try: events.append(json.loads(line))
            except json.JSONDecodeError as exc: raise ValueError(f"Invalid JSON in {EVENTS.name} line {line_no}: {exc}")
    return events

def choose_next(events=None):
    events = read_events() if events is None else events
    by_id={}
    for event in events:
        oid=event.get("opportunity_id")
        if oid: by_id.setdefault(oid,[]).append(event)
    candidates=generate()["opportunities"]
    # Continue the most recently selected unfinished experiment first.
    for event in reversed(events):
        oid=event.get("opportunity_id")
        history=by_id.get(oid, [])
        if oid and history and history[-1].get("status") not in TERMINAL:
            for idea in candidates:
                if idea["id"] == oid:
                    return idea, history
    # Otherwise pick an untested or least-tested idea. Stable ordering is auditable.
    candidates.sort(key=lambda item:(len(by_id.get(item["id"],[])), item["id"]))
    for idea in candidates:
        history=by_id.get(idea["id"],[])
        if not history or history[-1].get("status") not in TERMINAL:
            return idea, history
    # All initial ideas have terminal outcomes: rotate to the least-tested one.
    idea=candidates[0]
    return idea, by_id.get(idea["id"],[])

def run_cycle():
    events=read_events()
    idea, history=choose_next(events)
    now=datetime.now(timezone.utc).isoformat()
    run_id=now.replace(':','').replace('-','')
    status="READY_FOR_ZERO_COST_TEST" if not history else "FOLLOW_UP_TEST_REQUIRED"
    state={
      "run_id":run_id,"generated_at_utc":now,"status":status,
      "selected_opportunity_id":idea["id"],"selected_customer":idea["customer"],
      "problem":idea["problem"],"deliverable":idea["deliverable"],
      "validation_test":idea["validation_test"],"revenue_path":idea["revenue_path"],
      "estimated_cost_ceiling_ngn":0,"ai_model_used":False,
      "external_outreach_performed":False,"money_movement_performed":False,
      "income_generated_or_verified":False,
      "recorded_events_for_opportunity":len(history),
      "next_instruction":"Create the sample deliverable. Record evidence and outcome before claiming demand or income. External contact/publication requires owner approval."
    }
    EVENTS.parent.mkdir(parents=True,exist_ok=True)
    NEXT.parent.mkdir(parents=True,exist_ok=True)
    STATE.write_text(json.dumps(state,indent=2,ensure_ascii=False)+'\n',encoding='utf-8')
    NEXT.write_text(
      '# APIP — Next Action\n\n'
      f'- Run: `{run_id}`\n- Status: **{status}**\n- Opportunity: **{idea["id"]}**\n'
      f'- Customer: {idea["customer"]}\n- Problem: {idea["problem"]}\n'
      f'- Deliverable: {idea["deliverable"]}\n- Zero-cost test: {idea["validation_test"]}\n'
      f'- Possible revenue path: {idea["revenue_path"]}\n\n'
      '## Financial truth\n\n'
      '- Verified income generated by this run: **0 / not established**\n'
      '- Spend ceiling: **NGN 0**\n- External outreach: **not performed**\n'
      '- Next: build the sample, then record evidence and outcome. Do not report a hypothesis as revenue.\n',encoding='utf-8')
    # Append a run event only if this run isn't already present (idempotency guard).
    if not any(e.get('run_id')==run_id for e in events):
        with EVENTS.open('a',encoding='utf-8') as f: f.write(json.dumps({"run_id":run_id,"at_utc":now,"opportunity_id":idea["id"],"status":"SELECTED"},ensure_ascii=False)+'\n')
    return state

def main():
    state=run_cycle()
    print('APIP cycle completed safely.')
    print('Selected:',state['selected_opportunity_id'])
    print('Next action: reports/apip-next-action.md')
    print('No AI call, outreach, spend, or money movement occurred.')
if __name__=='__main__': main()
